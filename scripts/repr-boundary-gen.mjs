#!/usr/bin/env node
//
// The representation-boundary differential generator (Phase 4, W4e).
//
//   node scripts/repr-boundary-gen.mjs --seeds 50            # seeds 0..49 (the gate's smoke run)
//   node scripts/repr-boundary-gen.mjs --seeds 500           # the nightly budget
//   node scripts/repr-boundary-gen.mjs --seeds 10 --first 100 --keep
//
// Each seed is one deterministic `#![no_std]` + `alloc` program that pairs producers and
// consumers of String / Vec / slice values across the boundaries the representation planner
// labels over: plain calls, `&mut` borrows crossing a call, host calls (`js_log_str`),
// fn-pointer dispatch, statics, and an exported `#[no_mangle]` round trip. The ONE source is
// compiled twice on the JIR lane — `js-opt=off` and `js-opt=on` — and both programs are run
// under node; they must print the same stdout and end the same way (exit class, not number).
// With the solver absent every value stays baseline and the two trivially agree; the harness
// must still build, run and compare, which is what the gate's 50-seed smoke run checks.
//
// A disagreement is SHRUNK: `rust_entry`'s generated statements are dropped one at a time, and a
// drop is kept while the program still compiles and still disagrees. The smallest repro is left
// in `build/repr-boundary/<seed>/shrunk.rs`, and the seed is printed — the same seed always
// regenerates the same program.

import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const root = path.dirname(scriptDir);

// ------------------------------------------------------------------------------- options

const argv = process.argv.slice(2);
const flag = (name, fallback) => {
  const index = argv.indexOf(name);
  return index === -1 ? fallback : Number(argv[index + 1]);
};
const seeds = flag("--seeds", NaN);
const first = flag("--first", 0);
const keep = argv.includes("--keep");
if (!Number.isInteger(seeds) || seeds < 1 || !Number.isInteger(first) || first < 0) {
  console.error("usage: repr-boundary-gen.mjs --seeds <count> [--first <seed>] [--keep]");
  process.exit(2);
}

// ------------------------------------------------------------------------------- generator

// mulberry32, exactly as scripts/fuzz/gen.mjs: reproducibility, not statistical quality.
function mulberry32(state) {
  let a = (state + 0x6d2b79f5) >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// The fixed cast: producers and consumers of String / Vec / slice, one per boundary kind. The
// seeds vary which pairs meet and with what values; every statement is one self-contained line
// so the shrinker can drop lines. Everything is defined behavior: indices are reduced modulo
// the length, values stay small enough that no arithmetic overflows.
const PRELUDE = `\
// Generated by scripts/repr-boundary-gen.mjs — seed SEED. Do not edit; regenerate from the seed.
#![no_std]
#![no_main]
#![allow(improper_ctypes)]

extern crate alloc;

use alloc::format;
use alloc::string::{String, ToString};
use alloc::vec;
use alloc::vec::Vec;

unsafe extern "C" {
    fn js_log_f64(x: f64);
    fn js_log_str(s: &str);
    fn js_abort(msg: &str) -> !;
}
fn print_usize(x: usize) { unsafe { js_log_f64(x as f64) } }
fn print_i32(x: i32) { unsafe { js_log_f64(x as f64) } }
fn print_str(s: &str) { unsafe { js_log_str(s) } }

#[panic_handler]
fn panic(_: &core::panic::PanicInfo) -> ! { unsafe { js_abort("panic") } }

// The static boundary: values that flow out of a \`static\`.
static WORDS: [&str; 5] = ["alpha", "beta", "gamma", "delta", "h\\u{e9}llo"];
static NUMS: [i32; 8] = [3, 1, 4, 1, 5, 9, 2, 6];

// Producers.
fn make_string(n: usize, sep: &str) -> String {
    let mut s = String::new();
    let mut i = 0;
    while i < n { s.push_str(WORDS[i % WORDS.len()]); s.push_str(sep); i += 1; }
    s
}
fn make_vec(n: usize) -> Vec<i32> {
    let mut v = Vec::with_capacity(n);
    let mut i = 0;
    while i < n { v.push(NUMS[i % NUMS.len()] + i as i32); i += 1; }
    v
}

// Consumers across the call boundary: by value, by reference, by slice.
fn consume_string(s: String) -> usize { s.len() }
fn string_stats(s: &str) -> usize {
    let mut ascii = 0;
    for b in s.as_bytes() { if *b < 128 { ascii += 1; } }
    s.len() + ascii
}
fn sum_slice(v: &[i32]) -> i32 { let mut t = 0; for x in v { t += *x; } t }
fn head_str(s: &str, n: usize) -> &str {
    let mut end = n.min(s.len());
    while !s.is_char_boundary(end) { end -= 1; }
    &s[..end]
}

// Consumers across a \`&mut\` boundary: the value is mutated where it does not live.
fn grow(s: &mut String, t: &str) { s.push_str(t); s.push('!'); }
fn push_all(v: &mut Vec<i32>, k: i32) { let mut i = 0; while i < k { v.push(i); i += 1; } }
fn drain_half(v: &mut Vec<i32>) -> i32 { let mut t = 0; while v.len() > 1 { t += v.remove(0); if v.len() % 2 == 0 { break; } } t }

// The export round trip: values that cross an exported #[no_mangle] boundary and come back.
#[unsafe(no_mangle)]
pub fn aux_vec_round_trip(mut v: Vec<i32>) -> Vec<i32> { v.push(7); v }
#[unsafe(no_mangle)]
pub fn aux_string_round_trip(s: String) -> String { let mut s = s; s.push_str("~"); s }
`;

// One statement per menu entry, each a closed block on one line. `r` is the PRNG.
const MENU = [
  // call: String producer -> by-value consumer.
  (r) => `    { let s = make_string(${r.int(1, 5)}, "${r.sep()}"); print_usize(consume_string(s)); }`,
  // call + slice: &str view of a String across a call.
  (r) => `    { let s = make_string(${r.int(1, 6)}, "${r.sep()}"); print_usize(string_stats(&s)); print_str(head_str(&s, ${r.int(0, 9)})); }`,
  // &mut: mutate a String across a call, observe through the host boundary.
  (r) => `    { let mut s = make_string(${r.int(0, 4)}, "${r.sep()}"); grow(&mut s, WORDS[${r.int(0, 4)}]); print_str(&s); print_usize(s.len()); }`,
  // host: a static str straight into the host call.
  (r) => `    { print_str(WORDS[${r.int(0, 4)}]); }`,
  // fn pointer over strings.
  (r) => `    { let f: fn(&str) -> usize = string_stats; print_usize(f(WORDS[${r.int(0, 4)}])); }`,
  // call: Vec producer -> slice consumer, subslice in bounds by construction.
  (r) => {
    const n = r.int(2, 9);
    const from = r.int(0, n - 1);
    return `    { let v = make_vec(${n}); print_i32(sum_slice(&v[${from}..${r.int(from, n)}])); }`;
  },
  // &mut: grow and shrink a Vec across calls.
  (r) => `    { let mut v = make_vec(${r.int(0, 5)}); push_all(&mut v, ${r.int(1, 6)}); print_i32(drain_half(&mut v)); print_usize(v.len()); }`,
  // fn pointer over a &mut Vec.
  (r) => `    { let f: fn(&mut Vec<i32>, i32) = push_all; let mut v = vec![${r.int(0, 9)}i32, ${r.int(0, 9)}]; f(&mut v, ${r.int(1, 5)}); print_i32(sum_slice(&v)); }`,
  // export round trip: Vec out and back.
  (r) => `    { let v = aux_vec_round_trip(make_vec(${r.int(0, 6)})); print_usize(v.len()); print_i32(sum_slice(&v)); }`,
  // export round trip: String out and back.
  (r) => `    { let s = aux_string_round_trip(make_string(${r.int(0, 3)}, "${r.sep()}")); print_str(&s); }`,
  // the fmt cluster: format! producing a String from mixed pieces.
  (r) => `    { let s = format!("{}-{}", WORDS[${r.int(0, 4)}], ${r.int(0, 99)}i32); print_usize(string_stats(&s)); print_str(&s); }`,
  // Vec<String>: element drop glue behind a collection boundary.
  (r) => `    { let mut vs: Vec<String> = Vec::new(); vs.push(make_string(${r.int(0, 3)}, "${r.sep()}")); vs.push(WORDS[${r.int(0, 4)}].to_string()); let mut t = 0; for s in &vs { t += s.len(); } print_usize(t); }`,
  // static -> Vec: collect out of a static slice.
  (r) => `    { let mut v: Vec<i32> = Vec::new(); for x in &NUMS[..${r.int(1, 8)}] { v.push(*x); } print_i32(sum_slice(&v)); }`,
  // raw view: a fresh allocation seen only as a Box (the W5f whitelist) — or, half the time,
  // two allocations whose addresses are compared first (the guard that must stay pinned).
  (r) =>
    r.int(0, 1)
      ? `    { let x = unsafe { let p = alloc::alloc::alloc(core::alloc::Layout::new::<u32>()) as *mut u32; *p = ${r.int(0, 99)}; let b: alloc::boxed::Box<u32> = core::mem::transmute(p); *b + ${r.int(0, 9)} }; print_usize(x as usize); }`
      : `    { let x = unsafe { let p = alloc::alloc::alloc(core::alloc::Layout::new::<u32>()) as *mut u32; let q = alloc::alloc::alloc(core::alloc::Layout::new::<u32>()) as *mut u32; *p = ${r.int(0, 99)}; *q = ${r.int(0, 99)}; let d = (p != q) as u32; let a: alloc::boxed::Box<u32> = core::mem::transmute(p); let b: alloc::boxed::Box<u32> = core::mem::transmute(q); *a + *b + d }; print_usize(x as usize); }`,
];

function generate(seed) {
  const random = mulberry32(seed * 2654435761 + 96321);
  const r = {
    int: (min, max) => min + Math.floor(random() * (max - min + 1)),
    sep: () => [" ", "-", "", "\\u{30}"][Math.floor(random() * 4)],
  };
  const statements = [];
  const count = r.int(6, 16);
  for (let i = 0; i < count; i += 1) statements.push(MENU[r.int(0, MENU.length - 1)](r));
  return { prelude: PRELUDE.replace("SEED", String(seed)), statements };
}

const source = ({ prelude, statements }) =>
  `${prelude}\n#[unsafe(no_mangle)]\npub fn rust_entry() {\n${statements.join("\n")}\n}\n`;

// ------------------------------------------------------------------------------- harness

const shim = readFileSync(path.join(root, "runtime", "shim.js"), "utf8");
const entry = readFileSync(path.join(scriptDir, "entry.js"), "utf8");
const MODES = ["off", "on"];

function buildSysroots() {
  for (const mode of MODES) {
    execFileSync(path.join(scriptDir, "build_sysroot.sh"), {
      env: { ...process.env, JS_EXTRA_ARGS: `js-opt=${mode}`, SKIP_BUILD: "1" },
      stdio: ["ignore", "ignore", "inherit"],
    });
  }
}

/** Compiles `src` in `mode` and runs it; null when it does not compile. */
function run(dir, src, mode) {
  const out = path.join(dir, `prog-${mode}.js`);
  const compile = spawnSync(path.join(scriptDir, "compile_core.sh"), [src, out], {
    env: { ...process.env, JS_EXTRA_ARGS: `js-lane=jir js-opt=${mode} js-opt-warnings=off`, SKIP_BUILD: "1" },
    encoding: "utf8",
  });
  if (compile.status !== 0) {
    writeFileSync(path.join(dir, `compile-${mode}.log`), `${compile.stdout}\n${compile.stderr}`);
    return null;
  }
  const program = shim + readFileSync(out, "utf8") + entry;
  const ran = spawnSync("node", ["-"], { input: program, encoding: "utf8" });
  // The exit STATUS is a class: a panic aborts on both sides, whatever number node picked.
  return { stdout: ran.stdout, aborted: ran.status !== 0 };
}

/** Compiles and runs both modes; the disagreement, or null when the two agree. */
function compare(dir, program) {
  writeFileSync(path.join(dir, "prog.rs"), program);
  const results = MODES.map((mode) => run(dir, path.join(dir, "prog.rs"), mode));
  if (results.some((result) => result === null)) return { kind: "compile" };
  const [off, on] = results;
  if (off.stdout !== on.stdout || off.aborted !== on.aborted) return { kind: "diverged", off, on };
  // Test-only: RCGJS_BOUNDARY_FAULT=<substring> declares a program mentioning the substring
  // divergent, so the shrinker and the failure report run without waiting for a miscompile:
  //   RCGJS_BOUNDARY_FAULT=aux_vec_round_trip node scripts/repr-boundary-gen.mjs --seeds 1
  const fault = process.env.RCGJS_BOUNDARY_FAULT;
  const body = program.slice(program.indexOf("pub fn rust_entry"));
  if (fault && body.includes(fault)) return { kind: "diverged", off, on };
  // An agreed abort would be a vacuous pass: the generator only emits defined, supported
  // behavior, so a program that dies on both sides is a generator (or support) bug to fix, and
  // everything after the abort went unexercised.
  if (off.aborted) return { kind: "aborted", off };
  return null;
}

/** Line-wise statement shrink: the smallest still-diverging program, written to shrunk.rs. */
function shrink(dir, generated) {
  let statements = [...generated.statements];
  let done = false;
  while (!done) {
    done = true;
    for (let index = 0; index < statements.length; index += 1) {
      const candidate = statements.filter((_, position) => position !== index);
      const program = source({ prelude: generated.prelude, statements: candidate });
      const verdict = compare(dir, program);
      if (verdict !== null && verdict.kind === "diverged") {
        statements = candidate;
        done = false;
        break;
      }
    }
  }
  const shrunk = source({ prelude: generated.prelude, statements });
  writeFileSync(path.join(dir, "shrunk.rs"), shrunk);
  compare(dir, shrunk); // leave the shrunk pair's outputs behind for the autopsy
  return statements.length;
}

function check(seed) {
  const dir = path.join(root, "build", "repr-boundary", String(seed));
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  const generated = generate(seed);
  const verdict = compare(dir, source(generated));
  if (verdict === null) {
    if (!keep) rmSync(dir, { recursive: true, force: true });
    return true;
  }
  if (verdict.kind === "compile") {
    console.error(`seed ${seed}: does not compile (a generator bug) — see ${dir}`);
    return false;
  }
  if (verdict.kind === "aborted") {
    console.error(`seed ${seed}: aborted in both modes — the generator emits only defined,`);
    console.error(`  supported behavior, so this is a menu bug; see ${dir}`);
    console.error(String(verdict.off.stdout).split("\n").slice(-3).join("\n"));
    return false;
  }
  const lines = shrink(dir, generated);
  console.error(`seed ${seed}: off and on disagree — shrunk to ${lines} statement(s) at ${dir}/shrunk.rs`);
  console.error(`  reproduce: node scripts/repr-boundary-gen.mjs --seeds 1 --first ${seed} --keep`);
  return false;
}

// ponytail: serial — spawnSync blocks the event loop anyway, and a seed is ~1 s; shard by
// --first/--seeds across processes if the nightly 500 ever needs to go faster.
buildSysroots();
const failures = [];
for (let index = 0; index < seeds; index += 1) {
  if (!check(first + index)) failures.push(first + index);
  if ((index + 1) % 25 === 0) console.log(`repr-boundary: ${index + 1}/${seeds} seeds checked`);
}
if (failures.length > 0) {
  console.error(`repr-boundary: ${failures.length}/${seeds} seed(s) fail: ${failures.join(", ")}`);
  process.exit(1);
}
console.log(`repr-boundary: ${seeds} seed(s) agree on js-lane=jir js-opt=off vs on`);
