#[inline]
fn search_u32(first: &[u32], last: &[u32], cp: u32) -> bool {
    let mut lo = 0usize;
    let mut hi = first.len();
    while lo < hi {
        let mid = lo + ((hi - lo) >> 1);
        if first[mid] <= cp {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    lo > 0 && cp <= last[lo - 1]
}

#[inline]
fn search_u16(first: &[u16], last: &[u16], cp: u16) -> bool {
    let mut lo = 0usize;
    let mut hi = first.len();
    while lo < hi {
        let mid = lo + ((hi - lo) >> 1);
        if first[mid] <= cp {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    lo > 0 && cp <= last[lo - 1]
}

/// ECMA-262 `\s` whitespace and line terminators (exact 25 code points, including U+FEFF).
#[inline]
pub fn is_js_space(ch: char) -> bool {
    let cp = ch as u32;
    if cp < 0x80 {
        return cp == 0x20 || (cp >= 0x09 && cp <= 0x0D);
    }
    matches!(
        cp,
        0x00A0 | 0x1680 | 0x2000..=0x200A | 0x2028 | 0x2029 | 0x202F | 0x205F | 0x3000 | 0xFEFF
    )
}

/// Matches `/[\p{P}\p{S}]/u`.
#[inline]
pub fn is_punct(ch: char) -> bool {
    let cp = ch as u32;
    if cp < 0x80 {
        return (PUNCT_ASCII[(cp >> 5) as usize] & (1u32 << (cp & 31))) != 0;
    }
    search_u32(&PUNCT_FIRST, &PUNCT_LAST, cp)
}

/// Matches `/[\s\p{P}\p{S}]/u`.
#[inline]
pub fn is_punct_or_space(ch: char) -> bool {
    is_js_space(ch) || is_punct(ch)
}

/// Matches `/[\p{Pi}\p{Ps}"']/u` (pedantic opening punctuation / quotes).
#[inline]
pub fn is_open_quote(ch: char) -> bool {
    let cp = ch as u32;
    if cp < 0x80 {
        return (OPEN_QUOTE_ASCII[(cp >> 5) as usize] & (1u32 << (cp & 31))) != 0;
    }
    search_u32(&OPEN_QUOTE_FIRST, &OPEN_QUOTE_LAST, cp)
}

/// Matches `/[\p{L}\p{N}]/u` for a BMP character (UTF-16 `prevChar`).
#[inline]
pub fn is_bmp_alnum(ch: char) -> bool {
    let cp = ch as u32;
    if cp < 0x80 {
        return (cp >= 0x30 && cp <= 0x39)
            || (cp >= 0x41 && cp <= 0x5A)
            || (cp >= 0x61 && cp <= 0x7A);
    }
    if cp > 0xFFFF {
        return false;
    }
    search_u16(&ALNUM_BMP_FIRST, &ALNUM_BMP_LAST, cp as u16)
}

/// Exact JS `String.prototype.trim`.
pub fn trim_js(s: &str) -> &str {
    trim_end_js(trim_start_js(s))
}

/// Exact JS `String.prototype.trimStart`.
pub fn trim_start_js(s: &str) -> &str {
    let start = trim_start_js_bytes(s.as_bytes());
    &s[start..]
}

/// Exact JS `String.prototype.trimEnd`.
pub fn trim_end_js(s: &str) -> &str {
    let bytes = s.as_bytes();
    let end = trim_end_js_bytes(bytes);
    &s[..end]
}

/// Decodes one valid UTF-8 scalar value at `bytes[pos..]`, returning `(ch, byte_len)`.
/// Fast O(1) path for ASCII without calling `$rt_bstr_sub_from` or `core::str::Chars`.
#[inline]
pub fn decode_utf8_at(bytes: &[u8], pos: usize) -> (char, usize) {
    let b0 = bytes[pos];
    if b0 < 0x80 {
        return (b0 as char, 1);
    }
    if b0 < 0xE0 {
        let cp = (((b0 & 0x1F) as u32) << 6) | ((bytes[pos + 1] & 0x3F) as u32);
        return (char::from_u32(cp).unwrap_or('\u{FFFD}'), 2);
    }
    if b0 < 0xF0 {
        let cp = (((b0 & 0x0F) as u32) << 12)
            | (((bytes[pos + 1] & 0x3F) as u32) << 6)
            | ((bytes[pos + 2] & 0x3F) as u32);
        return (char::from_u32(cp).unwrap_or('\u{FFFD}'), 3);
    }
    let cp = (((b0 & 0x07) as u32) << 18)
        | (((bytes[pos + 1] & 0x3F) as u32) << 12)
        | (((bytes[pos + 2] & 0x3F) as u32) << 6)
        | ((bytes[pos + 3] & 0x3F) as u32);
    (char::from_u32(cp).unwrap_or('\u{FFFD}'), 4)
}

/// Decodes one valid UTF-8 scalar value immediately before `bytes[end]`, returning `(ch, byte_len)`.
#[inline]
pub fn decode_utf8_rev(bytes: &[u8], end: usize) -> (char, usize) {
    let b = bytes[end - 1];
    if b < 0x80 {
        return (b as char, 1);
    }
    let mut start = end - 1;
    while start > 0 && (bytes[start] & 0xC0) == 0x80 {
        start -= 1;
    }
    decode_utf8_at(bytes, start)
}

/// If `bytes[pos..]` starts with a JS whitespace character, returns its UTF-8 byte length.
#[inline]
pub fn js_space_len_at(bytes: &[u8], pos: usize) -> usize {
    if pos >= bytes.len() {
        return 0;
    }
    let b = bytes[pos];
    if b < 0x80 {
        if b == b' ' || (b >= 0x09 && b <= 0x0D) {
            1
        } else {
            0
        }
    } else {
        let (ch, len) = decode_utf8_at(bytes, pos);
        if is_js_space(ch) { len } else { 0 }
    }
}

/// If `bytes[pos..]` starts with an ECMA-262 line terminator (`\n`, `\r`, U+2028, U+2029),
/// returns its UTF-8 byte length. A regex `.` without the `s` flag matches every code unit
/// except these four, so the scanners that stand for `.` stop at them.
#[inline]
pub fn line_terminator_len_at(bytes: &[u8], pos: usize) -> usize {
    let n = bytes.len();
    if pos >= n {
        return 0;
    }
    match bytes[pos] {
        b'\n' | b'\r' => 1,
        // U+2028 and U+2029 are `E2 80 A8` and `E2 80 A9` in UTF-8.
        0xE2 if pos + 2 < n && bytes[pos + 1] == 0x80 && matches!(bytes[pos + 2], 0xA8 | 0xA9) => 3,
        _ => 0,
    }
}

/// End of the run a regex `.*` matches from `start`: the first line terminator, or the end.
#[inline]
pub fn dot_run_end(bytes: &[u8], start: usize) -> usize {
    let mut i = start;
    while i < bytes.len() && line_terminator_len_at(bytes, i) == 0 {
        i += 1;
    }
    i
}

/// Returns byte index of first non-JS-whitespace char in `bytes`.
#[inline]
pub fn trim_start_js_bytes(bytes: &[u8]) -> usize {
    let mut i = 0;
    while i < bytes.len() {
        let sl = js_space_len_at(bytes, i);
        if sl > 0 {
            i += sl;
        } else {
            break;
        }
    }
    i
}

/// Returns byte length after stripping trailing JS whitespace from `bytes`.
#[inline]
pub fn trim_end_js_bytes(bytes: &[u8]) -> usize {
    let mut end = bytes.len();
    while end > 0 {
        let (ch, len) = decode_utf8_rev(bytes, end);
        if is_js_space(ch) {
            end -= len;
        } else {
            break;
        }
    }
    end
}

/// Returns `true` if `bytes[start..end]` contains only JS whitespace (or is empty).
#[inline]
pub fn is_all_js_space_bytes(bytes: &[u8], start: usize, end: usize) -> bool {
    let mut i = start;
    while i < end {
        let sl = js_space_len_at(bytes, i);
        if sl == 0 {
            return false;
        }
        i += sl;
    }
    true
}

/// Mirrors JS `prevChar = token.raw.slice(-1)` in `Lexer.inlineTokens`:
/// an astral scalar value yields a lone UTF-16 low surrogate, which matches neither
/// `unicodeAlphaNumeric` nor `punctuation` nor `*`/`_`.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum PrevChar {
    None,
    Bmp(char),
    AstralLowSurrogate,
}

impl PrevChar {
    #[inline]
    pub fn from_last_byte_slice(bytes: &[u8]) -> Self {
        if bytes.is_empty() {
            return PrevChar::None;
        }
        let (ch, _) = decode_utf8_rev(bytes, bytes.len());
        if (ch as u32) > 0xFFFF {
            PrevChar::AstralLowSurrogate
        } else {
            PrevChar::Bmp(ch)
        }
    }

    #[inline]
    pub fn is_empty(self) -> bool {
        matches!(self, PrevChar::None)
    }

    #[inline]
    pub fn is_char(self, target: char) -> bool {
        matches!(self, PrevChar::Bmp(c) if c == target)
    }

    #[inline]
    pub fn is_unicode_alnum(self) -> bool {
        match self {
            PrevChar::Bmp(c) => is_bmp_alnum(c),
            PrevChar::None | PrevChar::AstralLowSurrogate => false,
        }
    }

    /// Matches `inline.punctuation`: `/^((?![*_])[\s\p{P}\p{S}])/u`.
    #[inline]
    pub fn is_inline_punctuation(self) -> bool {
        match self {
            PrevChar::Bmp(c) => c != '*' && c != '_' && is_punct_or_space(c),
            PrevChar::None | PrevChar::AstralLowSurrogate => false,
        }
    }
}
