//! Runtime entry point (`#[lang = "start"]`) and panic forwarding hooks.

pub use crate::panicking::{begin_panic, catch_unwind_message};
pub use core_crate::panicking::{panic_display, panic_fmt};

/// Unwind-capable static-message panic entry point (const-eval safe).
#[doc(hidden)]
#[inline(always)]
#[track_caller]
pub const fn panic_static(msg: &'static str) -> ! {
    core_crate::intrinsics::const_eval_select(
        (msg,),
        core_crate::panicking::panic,
        crate::panicking::panic_with_static_str,
    )
}

/// Unwind-capable formatted panic entry point (const-eval safe).
#[doc(hidden)]
#[inline(always)]
#[track_caller]
pub const fn panic_fmt_rt(args: core_crate::fmt::Arguments<'_>) -> ! {
    core_crate::intrinsics::const_eval_select(
        (args,),
        core_crate::panicking::panic_fmt,
        crate::panicking::panic_with_fmt,
    )
}

/// Entry point generated by `rustc` for binary crates (`fn main()`).
#[lang = "start"]
fn lang_start<T: crate::process::Termination + 'static>(
    main: fn() -> T,
    argc: isize,
    argv: *const *const u8,
    sigpipe: u8,
) -> isize {
    let _ = (argc, argv, sigpipe);
    let code = main().report();
    crate::io::stdio::flush_stdio();
    code.to_isize()
}
