/// Type of test according to Cargo conventions.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash)]
pub enum TestType {
    /// Unit test inside `src/`.
    UnitTest,
    /// Integration test inside `tests/`.
    IntegrationTest,
    /// Doctest generated by `rustdoc`.
    DocTest,
    /// Standalone test compiled directly with `rustc --test`.
    Unknown,
}

/// Padding hint used by `libtest` formatters.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum NamePadding {
    PadNone,
    PadOnRight,
}

/// Whether a test is expected to panic.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash)]
pub enum ShouldPanic {
    No,
    Yes,
    YesWithMessage(&'static str),
}

/// The name of a test case.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub enum TestName {
    StaticTestName(&'static str),
    DynTestName(String),
    AlignedTestName(Cow<'static, str>, NamePadding),
}

impl TestName {
    #[must_use]
    pub fn as_slice(&self) -> &str {
        match self {
            StaticTestName(s) => s,
            DynTestName(s) => s.as_str(),
            AlignedTestName(s, _) => s.as_ref(),
        }
    }

    #[must_use]
    pub fn padding(&self) -> NamePadding {
        match self {
            AlignedTestName(_, p) => *p,
            _ => PadNone,
        }
    }

    #[must_use]
    pub fn with_padding(&self, padding: NamePadding) -> TestName {
        let name = match self {
            StaticTestName(s) => Cow::Borrowed(*s),
            DynTestName(s) => Cow::Owned(s.clone()),
            AlignedTestName(s, _) => s.clone(),
        };
        AlignedTestName(name, padding)
    }
}

impl fmt::Display for TestName {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_slice())
    }
}

/// Summary statistics compatibility module for crates referencing `test::stats`.
pub mod stats {
    #[derive(Clone, Copy, Debug, Default, PartialEq)]
    pub struct Summary {
        pub sum: f64,
        pub min: f64,
        pub max: f64,
        pub mean: f64,
        pub median: f64,
        pub var: f64,
        pub std_dev: f64,
        pub std_dev_pct: f64,
        pub median_abs_dev: f64,
        pub median_abs_dev_pct: f64,
        pub quartiles: (f64, f64, f64),
        pub iqr: f64,
    }
}

/// Minimal `Bencher` compatibility stub for crates with `#[bench]` items.
#[derive(Clone, Debug, Default)]
pub struct Bencher {
    pub bytes: u64,
}

impl Bencher {
    /// Runs `inner` once when benchmarks are executed in test mode.
    pub fn iter<T, F>(&mut self, mut inner: F)
    where
        F: FnMut() -> T,
    {
        let _ = black_box(inner());
    }

    /// Runs a benchmark closure returning `Result<(), String>`.
    pub fn bench<F>(&mut self, mut f: F) -> Result<Option<stats::Summary>, String>
    where
        F: FnMut(&mut Bencher) -> Result<(), String>,
    {
        f(self).map(|()| None)
    }
}

/// Identity optimization barrier matching `test::black_box`.
#[inline(always)]
pub fn black_box<T>(dummy: T) -> T {
    core::hint::black_box(dummy)
}

/// Runnable test or benchmark entry point.
pub enum TestFn {
    StaticTestFn(fn() -> Result<(), String>),
    StaticBenchFn(fn(&mut Bencher) -> Result<(), String>),
    StaticBenchAsTestFn(fn(&mut Bencher) -> Result<(), String>),
    DynTestFn(Box<dyn FnOnce() -> Result<(), String> + Send>),
    DynBenchFn(Box<dyn Fn(&mut Bencher) -> Result<(), String> + Send>),
    DynBenchAsTestFn(Box<dyn Fn(&mut Bencher) -> Result<(), String> + Send>),
}

impl TestFn {
    #[must_use]
    pub fn padding(&self) -> NamePadding {
        match self {
            StaticBenchFn(..) | DynBenchFn(..) => PadOnRight,
            _ => PadNone,
        }
    }

    fn is_bench(&self) -> bool {
        matches!(self, StaticBenchFn(..) | DynBenchFn(..))
    }
}

impl fmt::Debug for TestFn {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            StaticTestFn(..) => f.write_str("StaticTestFn(..)"),
            StaticBenchFn(..) => f.write_str("StaticBenchFn(..)"),
            StaticBenchAsTestFn(..) => f.write_str("StaticBenchAsTestFn(..)"),
            DynTestFn(..) => f.write_str("DynTestFn(..)"),
            DynBenchFn(..) => f.write_str("DynBenchFn(..)"),
            DynBenchAsTestFn(..) => f.write_str("DynBenchAsTestFn(..)"),
        }
    }
}

/// Static metadata emitted by `rustc --test` for every test item.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct TestDesc {
    pub name: TestName,
    pub ignore: bool,
    pub ignore_message: Option<&'static str>,
    pub source_file: &'static str,
    pub start_line: usize,
    pub start_col: usize,
    pub end_line: usize,
    pub end_col: usize,
    pub compile_fail: bool,
    pub no_run: bool,
    pub should_panic: ShouldPanic,
    pub test_type: TestType,
}

impl TestDesc {
    #[must_use]
    pub fn padded_name(&self, column_count: usize, align: NamePadding) -> String {
        let mut name = String::from(self.name.as_slice());
        let fill = column_count.saturating_sub(name.len());
        let pad = " ".repeat(fill);
        match align {
            PadNone => name,
            PadOnRight => {
                name.push_str(&pad);
                name
            }
        }
    }

    #[must_use]
    pub fn test_mode(&self) -> Option<&'static str> {
        if self.ignore {
            return None;
        }
        match self.should_panic {
            ShouldPanic::Yes | ShouldPanic::YesWithMessage(_) => return Some("should panic"),
            ShouldPanic::No => {}
        }
        if self.compile_fail {
            return Some("compile fail");
        }
        if self.no_run {
            return Some("compile");
        }
        None
    }
}

/// Descriptor paired with its test function, generated by `rustc --test`.
#[derive(Debug)]
pub struct TestDescAndFn {
    pub desc: TestDesc,
    pub testfn: TestFn,
}

impl TestDescAndFn {
    #[must_use]
    pub const fn new_doctest(
        test_name: &'static str,
        ignore: bool,
        source_file: &'static str,
        start_line: usize,
        no_run: bool,
        should_panic: bool,
        testfn: TestFn,
    ) -> Self {
        Self {
            desc: TestDesc {
                name: StaticTestName(test_name),
                ignore,
                ignore_message: None,
                source_file,
                start_line,
                start_col: 0,
                end_line: 0,
                end_col: 0,
                compile_fail: false,
                no_run,
                should_panic: if should_panic {
                    ShouldPanic::Yes
                } else {
                    ShouldPanic::No
                },
                test_type: TestType::DocTest,
            },
            testfn,
        }
    }
}

/// Caller-supplied options for [`test_main`].
#[derive(Copy, Clone, Debug, Default)]
pub struct Options {
    pub display_output: bool,
    pub panic_abort: bool,
}

impl Options {
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    #[must_use]
    pub fn display_output(mut self, display_output: bool) -> Self {
        self.display_output = display_output;
        self
    }

    #[must_use]
    pub fn panic_abort(mut self, panic_abort: bool) -> Self {
        self.panic_abort = panic_abort;
        self
    }
}

/// Checks the [`Termination`] return value of a `#[test]` function.
pub fn assert_test_result<T: Termination>(result: T) -> Result<(), String> {
    let code = result.report();
    if code == ExitCode::SUCCESS {
        Ok(())
    } else {
        Err(format!(
            "the test returned a termination value with a non-zero status code ({code:?}) which indicates a failure"
        ))
    }
}

/// Entry point called by `rustc --test` under `-Cpanic=unwind`.
#[inline(always)]
pub fn test_main_static(tests: &[&TestDescAndFn]) {
    __mires_test_main_static(tests);
}

/// Entry point called by `rustc --test` under `-Cpanic=abort`.
#[inline(always)]
pub fn test_main_static_abort(tests: &[&TestDescAndFn]) {
    __mires_test_main_static(tests);
}

/// Unminified harness entry symbol so `cargo mires test` can reliably locate the
/// test binary's `main` caller even under `js-minify=on` release profiles.
#[unsafe(no_mangle)]
#[inline(never)]
pub fn __mires_test_main_static(tests: &[&TestDescAndFn]) {
    let owned: Vec<TestDescAndFn> = tests
        .iter()
        .map(|entry| match entry.testfn {
            StaticTestFn(f) => TestDescAndFn {
                desc: entry.desc.clone(),
                testfn: StaticTestFn(f),
            },
            StaticBenchFn(f) => TestDescAndFn {
                desc: entry.desc.clone(),
                testfn: StaticBenchAsTestFn(f),
            },
            StaticBenchAsTestFn(f) => TestDescAndFn {
                desc: entry.desc.clone(),
                testfn: StaticBenchAsTestFn(f),
            },
            _ => panic!("non-static test passed to test::test_main_static"),
        })
        .collect();
    let args = read_harness_args();
    test_main(&args, owned, None);
}

/// Runs a list of tests using `libtest`-compatible filtering, reporting, and exit codes.
pub fn test_main(args: &[String], tests: Vec<TestDescAndFn>, _options: Option<Options>) {
    let opts = parse_harness_args(args);

    let mut selected: Vec<TestDescAndFn> = Vec::with_capacity(tests.len());
    let mut filtered_out: usize = 0;

    for test in tests {
        if should_filter_out(&test.desc, &opts) {
            filtered_out += 1;
        } else {
            selected.push(test);
        }
    }

    if opts.list {
        for test in &selected {
            let kind = if test.testfn.is_bench() {
                "benchmark"
            } else {
                "test"
            };
            std::println!("{}: {kind}", test.desc.name.as_slice());
        }
        flush_all();
        return;
    }

    let started = Instant::now();
    let total = selected.len();
    let noun = if total == 1 { "test" } else { "tests" };
    std::println!();
    std::println!("running {total} {noun}");

    let mut passed: usize = 0;
    let mut failed: usize = 0;
    let mut ignored: usize = 0;
    let mut failures: Vec<(String, String)> = Vec::new();

    for test in selected {
        let name = String::from(test.desc.name.as_slice());
        let run_this_ignored = match opts.run_ignored {
            RunIgnored::No => false,
            RunIgnored::Yes | RunIgnored::Only => true,
        };

        if test.desc.ignore && !run_this_ignored {
            ignored += 1;
            if let Some(reason) = test.desc.ignore_message {
                std::println!("test {name} ... ignored, {reason}");
            } else {
                std::println!("test {name} ... ignored");
            }
            continue;
        }

        let suffix = match test.desc.test_mode() {
            Some(mode) => format!(" - {mode}"),
            None => String::new(),
        };

        match execute_single_test(test.desc.should_panic, test.testfn) {
            Outcome::Passed => {
                passed += 1;
                std::println!("test {name}{suffix} ... ok");
            }
            Outcome::Failed(detail) => {
                failed += 1;
                std::println!("test {name}{suffix} ... FAILED");
                failures.push((name, detail));
            }
        }
    }

    if !failures.is_empty() {
        std::println!();
        std::println!("failures:");
        std::println!();
        for (name, detail) in &failures {
            std::println!("---- {name} stdout ----");
            std::println!("{detail}");
        }
        std::println!();
        std::println!("failures:");
        for (name, _) in &failures {
            std::println!("    {name}");
        }
    }

    let elapsed = started.elapsed().as_secs_f64();
    let status = if failed == 0 { "ok" } else { "FAILED" };
    std::println!();
    std::println!(
        "test result: {status}. {passed} passed; {failed} failed; {ignored} ignored; 0 measured; {filtered_out} filtered out; finished in {elapsed:.2}s"
    );
    std::println!();
    flush_all();

    if failed > 0 && !host_set_exit_code(101) {
        std::process::exit(101);
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum RunIgnored {
    No,
    Yes,
    Only,
}

#[derive(Debug)]
struct HarnessOpts {
    filters: Vec<String>,
    skip: Vec<String>,
    exact: bool,
    run_ignored: RunIgnored,
    list: bool,
}

fn parse_harness_args(args: &[String]) -> HarnessOpts {
    let mut opts = HarnessOpts {
        filters: Vec::new(),
        skip: Vec::new(),
        exact: false,
        run_ignored: RunIgnored::No,
        list: false,
    };

    let mut i = 0;
    let mut after_double_dash = false;
    while i < args.len() {
        let arg = args[i].as_str();
        if after_double_dash {
            opts.filters.push(args[i].clone());
            i += 1;
            continue;
        }
        match arg {
            "--" => {
                after_double_dash = true;
            }
            "--exact" => {
                opts.exact = true;
            }
            "--ignored" => {
                opts.run_ignored = RunIgnored::Only;
            }
            "--include-ignored" => {
                opts.run_ignored = RunIgnored::Yes;
            }
            "--list" => {
                opts.list = true;
            }
            "--skip" => {
                if let Some(pat) = args.get(i + 1) {
                    opts.skip.push(pat.clone());
                    i += 1;
                }
            }
            "--test-threads" | "--color" | "--format" | "--logfile" | "--shuffle-seed" | "-Z" => {
                // Accepted for CLI compatibility with upstream `libtest`; skip value.
                i += 1;
            }
            "--nocapture"
            | "--show-output"
            | "-q"
            | "--quiet"
            | "--test"
            | "--bench"
            | "--report-time"
            | "--ensure-time"
            | "--shuffle"
            | "--force-run-in-process" => {}
            _ if arg.starts_with("--skip=") => {
                opts.skip.push(String::from(&arg["--skip=".len()..]));
            }
            _ if arg.starts_with("--test-threads=")
                || arg.starts_with("--color=")
                || arg.starts_with("--format=")
                || arg.starts_with("--logfile=")
                || arg.starts_with("--shuffle-seed=") => {}
            _ if arg.starts_with('-') => {}
            _ => {
                opts.filters.push(args[i].clone());
            }
        }
        i += 1;
    }

    opts
}

fn matches_pattern(name: &str, pat: &str, exact: bool) -> bool {
    if exact {
        name == pat
    } else {
        name.contains(pat)
    }
}

fn should_filter_out(desc: &TestDesc, opts: &HarnessOpts) -> bool {
    let name = desc.name.as_slice();
    if opts.run_ignored == RunIgnored::Only && !desc.ignore {
        return true;
    }
    if !opts.filters.is_empty()
        && !opts
            .filters
            .iter()
            .any(|pat| matches_pattern(name, pat, opts.exact))
    {
        return true;
    }
    if opts
        .skip
        .iter()
        .any(|pat| matches_pattern(name, pat, opts.exact))
    {
        return true;
    }
    false
}

enum Outcome {
    Passed,
    Failed(String),
}

fn execute_single_test(should_panic: ShouldPanic, testfn: TestFn) -> Outcome {
    struct TestRun {
        testfn: Option<TestFn>,
        caught: Option<Result<Result<(), String>, Box<dyn Any + Send>>>,
    }

    fn run_inner(raw: *mut u8) {
        // SAFETY: `raw` points to the caller's live `TestRun` for the synchronous call.
        let state = unsafe { &mut *(raw as *mut TestRun) };
        if let Some(tf) = state.testfn.take() {
            state.caught = Some(catch_unwind(AssertUnwindSafe(move || invoke_test_fn(tf))));
        }
    }

    let prev_depth = std::rt::panic_depth();
    let mut state = TestRun {
        testfn: Some(testfn),
        caught: None,
    };
    let raw = (&mut state as *mut TestRun).cast::<u8>();
    let escaped_msg = host_try_catch_all(run_inner, raw);

    let caught = if let Some(caught) = state.caught.take() {
        caught
    } else if let Some(payload) = std::rt::take_panic_payload(prev_depth) {
        Err(payload)
    } else if let Some(abort_msg) = escaped_msg.strip_prefix("rust abort: ") {
        if abort_msg.starts_with("rustc_codegen_js:") {
            return Outcome::Failed(format!("runtime error: {abort_msg}"));
        }
        Err(Box::new(String::from(abort_msg)) as Box<dyn Any + Send>)
    } else {
        return Outcome::Failed(format!("runtime error: {escaped_msg}"));
    };

    match (should_panic, caught) {
        (ShouldPanic::No, Ok(Ok(()))) => Outcome::Passed,
        (ShouldPanic::No, Ok(Err(msg))) => Outcome::Failed(format!("Error: {msg}")),
        (ShouldPanic::No, Err(payload)) => {
            let msg = extract_panic_str(&*payload).unwrap_or("Box<dyn Any>");
            Outcome::Failed(format!("thread 'main' panicked:\n{msg}"))
        }
        (ShouldPanic::Yes, Ok(Ok(()))) => {
            Outcome::Failed(String::from("note: test did not panic as expected"))
        }
        (ShouldPanic::Yes, Ok(Err(msg))) => Outcome::Failed(format!(
            "note: test did not panic as expected (returned Err: {msg})"
        )),
        (ShouldPanic::Yes, Err(_)) => Outcome::Passed,
        (ShouldPanic::YesWithMessage(expected), Ok(Ok(()))) => Outcome::Failed(format!(
            "note: test did not panic as expected (expected substring: {expected:?})"
        )),
        (ShouldPanic::YesWithMessage(expected), Ok(Err(msg))) => Outcome::Failed(format!(
            "note: test did not panic as expected (expected substring: {expected:?}; returned Err: {msg})"
        )),
        (ShouldPanic::YesWithMessage(expected), Err(payload)) => {
            match extract_panic_str(&*payload) {
                Some(actual) if actual.contains(expected) => Outcome::Passed,
                Some(actual) => Outcome::Failed(format!(
                    "panic did not contain expected string\n      panic message: {actual:?},\n expected substring: {expected:?}"
                )),
                None => Outcome::Failed(format!(
                    "panic did not contain expected string\n      panic message: Box<dyn Any>,\n expected substring: {expected:?}"
                )),
            }
        }
    }
}

fn invoke_test_fn(testfn: TestFn) -> Result<(), String> {
    match testfn {
        StaticTestFn(f) => f(),
        StaticBenchFn(f) | StaticBenchAsTestFn(f) => {
            let mut bencher = Bencher::default();
            f(&mut bencher)
        }
        DynTestFn(f) => f(),
        DynBenchFn(f) | DynBenchAsTestFn(f) => {
            let mut bencher = Bencher::default();
            f(&mut bencher)
        }
    }
}

fn extract_panic_str<'a>(payload: &'a (dyn Any + Send)) -> Option<&'a str> {
    if let Some(s) = payload.downcast_ref::<&'static str>() {
        Some(*s)
    } else if let Some(s) = payload.downcast_ref::<String>() {
        Some(s.as_str())
    } else {
        None
    }
}

fn flush_all() {
    let _ = std::io::stdout().flush();
    let _ = std::io::stderr().flush();
}

/// Reads harness arguments passed by the JS host (`globalThis.__mires_test_args`
/// if present, otherwise `process.argv.slice(2)`), delimited by ASCII US (`0x1f`).
fn read_harness_args() -> Vec<String> {
    let raw = host_test_args_raw();
    if raw.is_empty() {
        return Vec::new();
    }
    raw.split('\u{001f}')
        .filter(|part| !part.is_empty())
        .map(ToString::to_string)
        .collect()
}

#[unsafe(link_section = r#"rcgjs.js.1.0.(typeof globalThis.__mires_test_args === "string" ? globalThis.__mires_test_args : (typeof process !== "undefined" && Array.isArray(process.argv) ? process.argv.slice(2).join(String.fromCharCode(31)) : ""))"#)]
#[inline(never)]
fn host_test_args_raw() -> &'static str {
    ""
}

#[unsafe(link_section = r#"rcgjs.js.1.1.(typeof process !== "undefined" ? (process.exitCode = _$js0, true) : false)"#)]
#[inline(never)]
fn host_set_exit_code(code: i32) -> bool {
    let _ = code;
    false
}

#[unsafe(link_section = r#"rcgjs.js.1.2.((fn, arg) => { try { fn(arg); return ""; } catch (e) { return String(e && typeof e === "object" && "message" in e ? e.message : e); } })(_$js0, _$js1)"#)]
#[inline(never)]
fn host_try_catch_all(f: fn(*mut u8), arg: *mut u8) -> &'static str {
    f(arg);
    ""
}
