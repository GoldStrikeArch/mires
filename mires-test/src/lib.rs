//! Lightweight `libtest` sysroot crate for the `mires` (Rust-to-JavaScript) compiler.
//!
//! Compiled as `--crate-name test --crate-type rlib` into the Mires sysroot so
//! ordinary Rust `#[test]` suites compiled via `rustc --test` / `cargo mires test`
//! execute natively in JavaScript runtimes with standard `libtest` semantics.

#![no_std]
#![allow(dead_code)]

